"""Writing generated tests: runner workbook, CSV and Markdown report."""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Sequence

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill

from matrixgen.catalog import Catalog
from matrixgen.coverage import CoverageReport
from matrixgen.space import Assignment

# The column layout excel-regression-runner reads (row 1 of each test sheet).
# This is a contract between the two projects: tests/test_writers.py pins it,
# and CI runs a generated workbook through the real runner.
RUNNER_HEADERS = [
    "ID", "Description", "Action", "Phone", "Params", "Expected Status", "Expected Response",
    "Actual Status", "Actual Response", "Result", "Details",
]

# Setup/cleanup rows pass whether the account was closed now (200), already
# closed (409) or never existed (404).
CLEANUP_STATUS = "200,404,409"
PHONE_POOL = 100  # 555-0100 .. 555-0199, the range reserved for fictional use

_WIDTHS = [11, 46, 9, 13, 30, 10, 34, 10, 40, 9, 50]
_HEADER_FILLS = ["DDEBF7"] * 5 + ["FFF2CC"] * 2 + ["E2EFDA"] * 4


def describe(test: Assignment) -> str:
    """'plan=plus, device=tablet, ...' for the Description column."""
    return ", ".join(f"{k}={v}" for k, v in test.items())


def phone_for(index: int, area_code: str) -> str:
    """Fictional 10-digit number for the index-th test (reused in rotation).

    Reuse is safe because every test closes its number at the end, and the
    setup row closes any leftover from an interrupted run.
    """
    return f"{area_code}55501{index % PHONE_POOL:02d}"


def runner_rows(tests: Sequence[Assignment], catalog: Catalog, prefix: str) -> list[list]:
    """Four runner rows per test: setup close, create, get, cleanup close."""
    rows = []
    for i, test in enumerate(tests, start=1):
        tid = f"{prefix}-{i:02d}"
        phone = phone_for(i - 1, catalog.area_code)
        params, checks, features = [], [], []
        for name, value in test.items():
            m = catalog.mapping[name]
            if m.kind == "param":
                params.append(f"{m.name}={value}")
                checks.append(f"{m.name}={value}")
            elif m.kind == "feature":
                on = value == m.enabled
                if on:
                    features.append(m.name)
                checks.append(f"features={m.name}" if on else f"!features={m.name}")
        if features:
            params.append("features=" + ",".join(features))
        expected = "\n".join(checks)
        combo = describe(test)
        rows += [
            [f"{tid}-S", f"Setup: clear {phone} if left over", "close", phone, "", CLEANUP_STATUS, ""],
            [f"{tid}-A", f"Create: {combo}", "create", phone, "\n".join(params), "201", expected],
            [f"{tid}-B", f"Read back: {combo}", "get", phone, "", "200",
             "status=active\n" + expected if expected else "status=active"],
            [f"{tid}-C", f"Clean up {tid}", "close", phone, "", "200", "status=closed"],
        ]
    return rows


def write_runner_workbook(tests: Sequence[Assignment], catalog: Catalog, path: str | Path,
                          sheet_name: str, prefix: str) -> int:
    """Write an excel-regression-runner workbook. Returns the number of test rows."""
    wb = Workbook()
    ws = wb.active
    ws.title = sheet_name
    ws.append(RUNNER_HEADERS)
    for col, (header, color, width) in enumerate(zip(RUNNER_HEADERS, _HEADER_FILLS, _WIDTHS), start=1):
        cell = ws.cell(row=1, column=col)
        cell.font = Font(bold=True)
        cell.fill = PatternFill("solid", start_color=color)
        ws.column_dimensions[cell.column_letter].width = width
    rows = runner_rows(tests, catalog, prefix)
    wrap = Alignment(wrap_text=True, vertical="top")
    for row in rows:
        ws.append(row)
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = wrap
        row[3].number_format = "@"  # phone as text
        row[5].number_format = "@"  # keeps "200,404,409" a list
    ws.freeze_panes = "C2"

    # Config sheet for the optional Excel macro front-end (see excel-regression-runner).
    cfg = wb.create_sheet("Config")
    cfg.append(["Python executable", r"C:\path\to\excel-regression-runner\.venv\Scripts\python.exe"])
    cfg.append(["Project folder", r"C:\path\to\excel-regression-runner"])
    cfg.append([])
    cfg.append(["Generated by test-matrix-generator. Save as .xlsm and import the runner macro to run from Excel."])
    cfg.column_dimensions["A"].width = 20
    cfg.column_dimensions["B"].width = 70
    wb.save(path)
    return len(rows)


def write_csv(tests: Sequence[Assignment], names: Sequence[str], path: str | Path) -> None:
    """One row per test, one column per parameter."""
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["test", *names])
        for i, test in enumerate(tests, start=1):
            writer.writerow([i, *(test[n] for n in names)])


def render_report(catalog: Catalog, strategy: str, tests: Sequence[Assignment],
                  coverage: CoverageReport, valid_total: int | None, seed: int | None) -> str:
    """A Markdown coverage report."""
    label = {2: "pairs", 3: "triples"}.get(coverage.strength, f"{coverage.strength}-way interactions")
    lines = [
        f"# Test matrix: {catalog.name}",
        "",
        "| | |",
        "|---|---|",
        f"| Strategy | {strategy} |",
        f"| Coverage strength | {coverage.strength} ({label}) |",
    ]
    if seed is not None:
        lines.append(f"| Seed | {seed} |")
    lines += [
        f"| Parameters | {len(catalog.parameters)} ({', '.join(catalog.parameters)}) |",
        f"| Rules | {len(catalog.rules)} |",
        f"| Combinations before rules | {catalog.space.size} |",
        f"| Valid combinations (exhaustive) | {valid_total if valid_total is not None else 'not counted'} |",
        f"| **Tests generated** | **{len(tests)}** |",
    ]
    if valid_total:
        lines.append(f"| Reduction vs exhaustive | {100 * (1 - len(tests) / valid_total):.0f}% fewer tests |")
    lines += [
        f"| Coverable {label} | {coverage.required} |",
        f"| Covered | {coverage.covered} ({coverage.percent:.1f}%) |",
        f"| Impossible under the rules | {len(coverage.impossible)} |",
        "",
        "## Rules",
        "",
        *([f"- `{r.text}`" for r in catalog.rules] or ["(none)"]),
        "",
        "## Tests",
        "",
        "| # | " + " | ".join(catalog.parameters) + " |",
        "|---|" + "---|" * len(catalog.parameters),
        *[f"| {i} | " + " | ".join(t[n] for n in catalog.parameters) + " |" for i, t in enumerate(tests, 1)],
    ]
    if coverage.impossible:
        lines += ["", f"## {label.capitalize()} the rules make impossible", ""]
        lines += [f"- {', '.join(f'{k}={v}' for k, v in inter)}" for inter in coverage.impossible]
    if coverage.missing:
        lines += ["", "## Not covered", ""]
        lines += [f"- {', '.join(f'{k}={v}' for k, v in inter)}" for inter in coverage.missing]
    return "\n".join(lines) + "\n"
